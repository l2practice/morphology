#!/usr/bin/env python3
"""Read the course's affix list (docs/Common_English_Prefixes_and_Suffixes.docx) and write
docs/course-affixes.json and course-affixes.js (loaded by the app for meanings).
usage: python3 -I tools/build-course-data.py"""
import zipfile, re, json, collections
x = zipfile.ZipFile("docs/Common_English_Prefixes_and_Suffixes.docx").read("word/document.xml").decode("utf8")
txt = lambda s: "".join(re.findall(r"<w:t[^>]*>([^<]*)</w:t>", s))
tables = []
for m in re.finditer(r"<w:tbl>.*?</w:tbl>", x, flags=re.S):
    rows = []
    for r in re.findall(r"<w:tr[ >].*?</w:tr>", m.group(0), flags=re.S):
        c = [txt(k).replace("`", "").strip() for k in re.findall(r"<w:tc>.*?</w:tc>", r, flags=re.S)]
        if c and c[0] != "Word Part" and c[0] != "Bound Morpheme":
            rows.append(c)
    tables.append(rows)
def affixes(rows):
    out = collections.OrderedDict()
    for r in rows:
        for f in r[1].lower().split("/"):
            f = f.strip().strip("-")
            e = out.setdefault(f, {"m": [], "ex": []})
            if r[2] not in e["m"]: e["m"].append(r[2])
            for w in re.split(r",\s*", r[3]):
                if w and w not in e["ex"]: e["ex"].append(w)
    return out
base = collections.OrderedDict()
for r in tables[2]:
    vs = [v.strip("-") for v in r[0].lower().split("/")]
    base[vs[0]] = {"v": vs, "m": r[1], "ex": [w for w in re.split(r",\s*", r[2]) if w], "o": r[3]}
data = {"prefix": affixes(tables[0]), "suffix": affixes(tables[1]), "base": base}
json.dump(data, open("docs/course-affixes.json", "w"), ensure_ascii=False, indent=1)
open("course-affixes.js", "w").write("/* Generated by tools/build-course-data.py from the course list. */\nwindow.COURSE_AFFIXES = " + json.dumps(data, ensure_ascii=False, separators=(",", ":")) + ";\n")
print({k: len(v) for k, v in data.items()})
